function scenarioById(result, id) {
  if (!result || !Array.isArray(result.scenarios)) return null;
  return result.scenarios.find((s) => s.id === id) || null;
}

function buildFailureTranscript(logic) {
  const bar = '='.repeat(72);
  const r = logic.result;
  const empty = scenarioById(r, 'guard-empty');
  const ws = scenarioById(r, 'guard-whitespace');
  const clob = scenarioById(r, 'guard-no-clobber');
  const save = scenarioById(r, 'save-after-guard');
  const lines = [];
  const push = (line) => lines.push(line);

  push(bar);
  push('# artifacts/qa/14-failure.txt — task 14 failure-path evidence');
  push('# command: node tests/e2e/profile.spec.mjs');
  push(`# timestamp: ${new Date().toISOString()}`);
  push(`# project: ${CONFIG.projectPath}`);
  push(`# method: real page methods from pages/profile/profile.ts via node tsx harness`);
  push(bar);
  push('');
  push('## (a) 称呼与年龄段均空 -> 提示且不写入（真实代码路径）');
  push('');
  if (empty !== null) {
    push(`scenario: ${empty.name}`);
    push('  input: form.name = "" , form.ageRange = "" (both empty after trim)');
    push(`  storage BEFORE: ${empty.details.before_bytes}`);
    push('  call: inst.onSave()  (pages/profile/profile.ts onSave)');
    push(`  toast recorded: ${JSON.stringify(empty.details.toast)}`);
    push(`  view errorText: ${JSON.stringify(empty.details.errorText)}`);
    push(`  storage AFTER : ${empty.details.after_bytes}`);
    push(`  bytes identical: ${empty.details.bytes_identical}`);
    push(`  storage keys after: ${JSON.stringify(empty.details.storage_keys)}`);
    push(`  assertion pass: ${empty.pass}`);
  } else {
    push('  MISSING: guard-empty scenario not found in harness result');
  }
  push('');
  push('assertion: 守卫在 records.profile.write 之前 return，存储逐字节不变（无 health_profile / records_profile 写入）。');
  push('');
  push('## (b) 纯空白同样被拦截');
  push('');
  if (ws !== null) {
    push(`scenario: ${ws.name}`);
    push('  input: form.name = "   " , form.ageRange = "  " (whitespace only)');
    push(`  storage BEFORE: ${ws.details.before_bytes}`);
    push(`  storage AFTER : ${ws.details.after_bytes}`);
    push(`  bytes identical: ${ws.details.bytes_identical}`);
    push(`  toast recorded: ${JSON.stringify(ws.details.toast)}`);
    push(`  assertion pass: ${ws.pass}`);
  } else {
    push('  MISSING: guard-whitespace scenario');
  }
  push('');
  push('## (c) 已有记录时守卫不覆盖（不写成空记录）');
  push('');
  if (clob !== null) {
    push(`scenario: ${clob.name}`);
    push(`  storage BEFORE: ${clob.details.before_bytes}`);
    push(`  storage AFTER : ${clob.details.after_bytes}`);
    push(`  bytes identical: ${clob.details.bytes_identical}`);
    push(`  record after attempt: ${JSON.stringify(clob.details.record)}`);
    push(`  assertion pass: ${clob.pass}`);
  } else {
    push('  MISSING: guard-no-clobber scenario');
  }
  push('');
  push('## (d) 守卫失败后保存路径仍然可用');
  push('');
  if (save !== null) {
    push(`scenario: ${save.name}`);
    push(`  record after valid save: ${JSON.stringify(save.details.record)}`);
    push(`  assertion pass: ${save.pass}`);
  } else {
    push('  MISSING: save-after-guard scenario');
  }
  push('');
  push('## verdict');
  push('');
  const verdict =
    empty !== null &&
    empty.pass &&
    empty.details.bytes_identical === true &&
    ws !== null &&
    ws.pass &&
    clob !== null &&
    clob.pass &&
    save !== null &&
    save.pass;
  push(`PASS=${verdict} (empty guard no-write; whitespace guard no-write; no clobber; save-after-guard works)`);
  push(bar);
  push('');
  return lines.join('\n');
}

