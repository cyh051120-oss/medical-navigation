// profile.spec.mjs — task 14 minimal-local-profile E2E (standalone).
//
// Run: node tests/e2e/profile.spec.mjs
// Evidence: artifacts/e2e/profile.json (harness + automator)
//           artifacts/qa/14-failure.txt (guard failure-path transcript)
//
// Two independent layers, never conflated:
//   (1) LOGIC (real code path): the page's own methods are exercised by importing
//       pages/profile/profile.ts into a node/page-logic harness (Page-capture + a
//       Map-backed wx shim), exactly the sanctioned pattern from check-brief.mjs.
//       This is the only way to reach onSave/onClear over this devtools build:
//       the Page.* automator protocol (page.$/page.data/evaluate) is dropped and
//       hangs, so the runtime cannot tap the form. The guard (both empty -> prompt,
//       no write) and save/read-back/update/clear are all driven through the REAL
//       page methods.
//   (2) RUNTIME (automator): launch the miniprogram, reLaunch to pages/profile,
//       screenshot (render proof), write a record into the runtime storage via
//       callWxMethod, reLaunch and observe the render change (namespace + read-back),
//       then relaunch to prove persistence. The runtime namespace is asserted to be
//       exactly `mhp_` (legacy `hza_` write is the negative control).
//
// Transport notes (WeChat DevTools 2.01.x): only App-level calls respond —
// currentPage/pageStack/screenshot/callWxMethod/reLaunch/close. Do NOT use Page.*.
