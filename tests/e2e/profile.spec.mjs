function runLogicHarness() {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'mhp-profile-harness-'));
  const harnessPath = path.join(tmpDir, 'profile-logic.harness.mjs');
  const outPath = path.join(tmpDir, 'profile-logic.result.json');
  fs.writeFileSync(harnessPath, HARNESS_SOURCE);

  const profileTsPath = path.join(PROFILE_DIR, 'profile.ts');
  const res = spawnSync(process.execPath, ['--import', 'tsx', harnessPath], {
    cwd: ROOT,
    encoding: 'utf8',
    env: { ...process.env, MHP_PROFILE_TS: profileTsPath, MHP_HARNESS_OUT: outPath },
    timeout: 60000,
    maxBuffer: 16 * 1024 * 1024,
  });
  const stdout = `${res.stdout || ''}`;
  const stderr = `${res.stderr || ''}`;

  let result = null;
  if (fs.existsSync(outPath)) {
    try {
      result = JSON.parse(fs.readFileSync(outPath, 'utf8'));
    } catch (err) {
      fail(`harness result JSON unparsable: ${err?.message || err}`);
    }
  }
  return {
    method: 'node --import tsx <temp harness> (Page-capture + Map wx shim)',
    profile_ts: profileTsPath,
    exit: res.status,
    stdout_tail: stdout.slice(-6000),
    stderr_tail: stderr.slice(-6000),
    result,
  };
}

