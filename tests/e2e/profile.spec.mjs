const FORBIDDEN_STRINGS = ['AI 注入', 'health_profile', 'hza_', 'System Prompt', '系统提示词'];

function staticInvariantChecks() {
  const ts = readPageBundle('profile', 'ts');
  const wxml = readPageBundle('profile', 'wxml');
  const wxss = readPageBundle('profile', 'wxss');
  const json = readPageBundle('profile', 'json');
  const combined = [ts, wxml, wxss, json].join('\n');

  const forbidden = FORBIDDEN_STRINGS.filter((term) => combined.includes(term));
  const usesRecordsApi = /records\.profile\.(add|update|remove|list)\s*\(/.test(ts);
  const directStorage = /wx\.(get|set|remove)StorageSync\s*\(/.test(ts);

  let jsonParses = false;
  let jsonTitle = null;
  try {
    const parsed = JSON.parse(json);
    jsonParses = true;
    jsonTitle = parsed.navigationBarTitleText ?? null;
  } catch {
    jsonParses = false;
  }

  const fontLines = wxss.split(/\r?\n/).filter((line) => line.includes('font-size'));
  const fontAllScaled =
    fontLines.length > 0 && fontLines.every((line) => /calc\([^)]*var\(--mhp-scale\)\)/.test(line));

  return {
    profile_js_exists: fs.existsSync(path.join(PROFILE_DIR, 'profile.js')),
    profile_ts_exists: fs.existsSync(path.join(PROFILE_DIR, 'profile.ts')),
    forbidden_strings_present: forbidden,
    uses_records_api: usesRecordsApi,
    direct_storage_calls: directStorage,
    json_parses: jsonParses,
    json_title: jsonTitle,
    font_size_lines: fontLines.length,
    font_size_all_scaled: fontAllScaled,
  };
}

