async function main() {
  ensureDir(E2E_DIR);
  ensureDir(path.dirname(QA_FAILURE_PATH));
  section('PROFILE SPEC');

  const report = {
    command: 'node tests/e2e/profile.spec.mjs',
    timestamp: new Date().toISOString(),
    platform: `${os.platform()} ${os.release()} (${os.arch()})`,
    node_version: process.version,
    project_path: CONFIG.projectPath,
    logic: null,
    render: null,
    render_saved: null,
    namespace: null,
    storage_readback: null,
    static_invariants: null,
    summary: null,
  };

  let allOk = true;

  // ---- Layer 1: real page logic ----
  const logic = runLogicHarness();
  report.logic = {
    method: logic.method,
    profile_ts: logic.profile_ts,
    exit: logic.exit,
    result: logic.result,
  };
  const logicScenarios = logic.result ? logic.result.scenarios : [];
  const logicFailed = logic.result ? logic.result.summary.failed : -1;
  if (logic.result !== null && logic.exit === 0 && logicFailed === 0) {
    ok(`logic harness: ${logic.result.summary.passed}/${logic.result.summary.total} scenarios passed (real page methods)`);
  } else {
    fail(`logic harness failed (exit=${logic.exit}, failed_scenarios=${logicFailed}); stderr tail: ${logic.stderr_tail}`);
    allOk = false;
  }
  for (const scenario of logicScenarios) {
    log(`  [logic] ${scenario.pass ? 'PASS' : 'FAIL'} ${scenario.id}: ${scenario.name}`);
    if (!scenario.pass) allOk = false;
  }

  // ---- Static invariants ----
  const statics = staticInvariantChecks();
  report.static_invariants = {
    profile_js_exists: statics.profile_js_exists,
    profile_ts_exists: statics.profile_ts_exists,
    forbidden_strings_present: statics.forbidden_strings_present,
    uses_records_api: statics.uses_records_api,
    direct_storage_calls: statics.direct_storage_calls,
    json_parses: statics.json_parses,
    json_title: statics.json_title,
    font_size_lines: statics.font_size_lines,
    font_size_all_scaled: statics.font_size_all_scaled,
  };
  if (
    statics.profile_js_exists === false &&
    statics.profile_ts_exists === true &&
    statics.forbidden_strings_present.length === 0 &&
    statics.uses_records_api &&
    !statics.direct_storage_calls &&
    statics.json_parses &&
    statics.json_title === '个人档案' &&
    statics.font_size_all_scaled
  ) {
    ok('static invariants: profile.js deleted; records API only; tokens/scale wxss; no forbidden strings');
  } else {
    fail(`static invariant failure: ${JSON.stringify(report.static_invariants)}`);
    allOk = false;
  }

  // ---- Layer 2: runtime ----
  let miniProgram;
  try {
    miniProgram = await launchMiniProgram();

    for (const ns of APP_NAMESPACES) {
      await miniProgram.callWxMethod('removeStorageSync', ns + PROFILE_RAW);
    }

    // warm-up + settle: the very first reLaunch can race the page's onShow render,
    // so the empty baseline is captured only after two settled reLaunches.
    await miniProgram.reLaunch('/' + PROFILE_ROUTE);
    await delay(800);
    await miniProgram.reLaunch('/' + PROFILE_ROUTE);
    await delay(800);
    const emptyRender = await renderEvidence(miniProgram, 'empty');
    report.render = { ...emptyRender, method: 'reLaunch+pageStack+screenshot' };
    if (emptyRender.ok) {
      ok(`render evidence: pageStack=${emptyRender.pageStack}, top=${emptyRender.topPath}, bytes=${emptyRender.screenshotBytes}, bytes>5000=${emptyRender.screenshotBytes > 5000}`);
    } else {
      fail(`render check failed: ${JSON.stringify(emptyRender)}`);
      allOk = false;
    }

    const sample = {
      id: 'prof_demo_1',
      createdAt: '2026-02-01T00:00:00.000Z',
      updatedAt: '2026-02-01T00:00:00.000Z',
      name: '李建国',
      ageRange: '60-69',
      gender: '男',
      allergies: '青霉素',
      medications: '氯沙坦',
      history: '高血压',
    };

    // negative control: legacy hza_ write must NOT change the render
    await miniProgram.callWxMethod('setStorageSync', 'hza_' + PROFILE_RAW, [sample]);
    await miniProgram.reLaunch('/' + PROFILE_ROUTE);
    await delay(800);
    const legacyShot = await captureScreenshot(miniProgram, 'legacy-hza');
    await miniProgram.callWxMethod('removeStorageSync', 'hza_' + PROFILE_RAW);
    const hzaChanged = legacyShot.md5 !== emptyRender.screenshotMd5;

    // positive: mhp_ write changes the render
    await miniProgram.callWxMethod('setStorageSync', 'mhp_' + PROFILE_RAW, [sample]);
    await miniProgram.reLaunch('/' + PROFILE_ROUTE);
    await delay(800);
    const savedRender = await renderEvidence(miniProgram, 'saved');
    const mhpChanged = savedRender.screenshotMd5 !== emptyRender.screenshotMd5;

    report.namespace = {
      declared: 'mhp_',
      candidates: APP_NAMESPACES,
      runtime_observed: mhpChanged && !hzaChanged ? 'mhp_' : null,
      empty_baseline_md5: emptyRender.screenshotMd5,
      observations: {
        mhp_: { md5: savedRender.screenshotMd5, bytes: savedRender.screenshotBytes, changed_vs_empty: mhpChanged },
        hza_: { md5: legacyShot.md5, bytes: legacyShot.bytes, changed_vs_empty: hzaChanged },
      },
    };
    report.render_saved = {
      ...savedRender,
      namespace: 'mhp_',
      changed_vs_empty_md5: mhpChanged,
    };

    if (report.namespace.runtime_observed === 'mhp_') {
      ok('runtime namespace is "mhp_" (mhp_ write changes render; hza_ does not)');
    } else {
      fail(`runtime namespace must be "mhp_" but observed ${JSON.stringify(report.namespace)}`);
      allOk = false;
    }
    if (savedRender.ok && mhpChanged) {
      ok('profile render reads the saved record (md5 changed vs empty)');
    } else {
      fail(`profile did not render the saved record: ${JSON.stringify(report.render_saved)}`);
      allOk = false;
    }

    // storage-level save -> read-back
    const readBack = await miniProgram.callWxMethod('getStorageSync', 'mhp_' + PROFILE_RAW);
    const matches = JSON.stringify(readBack) === JSON.stringify([sample]);
    report.storage_readback = {
      key: 'mhp_records_profile',
      written: [sample],
      read_back: readBack,
      matches,
      persisted_after_relaunch: null,
    };
    if (matches) {
      ok('storage read-back matches the written record exactly');
    } else {
      fail(`storage read-back mismatch: ${JSON.stringify(readBack)}`);
      allOk = false;
    }

    // relaunch persistence
    try {
      await miniProgram.close();
      log('miniProgram.close() done');
    } catch (err) {
      log(`warning: close failed: ${err?.message || err}`);
    }
    await delay(2000);
    miniProgram = await launchMiniProgram();
    const persisted = await miniProgram.callWxMethod('getStorageSync', 'mhp_' + PROFILE_RAW);
    const persistedOk = JSON.stringify(persisted) === JSON.stringify([sample]);
    report.storage_readback.persisted_after_relaunch = persistedOk;
    if (persistedOk) {
      ok('saved record persists across a full relaunch');
    } else {
      fail(`record did not persist across relaunch: ${JSON.stringify(persisted)}`);
      allOk = false;
    }

    // cleanup runtime storage (leave the project clean)
    for (const ns of APP_NAMESPACES) {
      await miniProgram.callWxMethod('removeStorageSync', ns + PROFILE_RAW);
    }
  } catch (err) {
    fail(`profile spec run error: ${err?.stack || err}`);
    report.error = err?.message || String(err);
    allOk = false;
  } finally {
    if (miniProgram) {
      try {
        await miniProgram.close();
        log('miniProgram.close() done');
      } catch (err) {
        log(`warning: miniProgram.close() failed: ${err?.message || err}`);
      }
    }
  }

  // ---- Failure transcript ----
  fs.writeFileSync(QA_FAILURE_PATH, buildFailureTranscript(logic));
  log(`failure evidence: ${QA_FAILURE_PATH}`);

  // ---- Summary ----
  const checks = {
    logic_harness_ok: logic.result !== null && logic.exit === 0 && logicFailed === 0,
    render_ok: report.render ? report.render.ok === true : false,
    namespace_observed: report.namespace ? report.namespace.runtime_observed === 'mhp_' : false,
    render_saved_ok: Boolean(
      report.render_saved && report.render_saved.ok && report.render_saved.changed_vs_empty_md5
    ),
    storage_readback_ok: Boolean(report.storage_readback && report.storage_readback.matches === true),
    relaunch_persistence_ok: Boolean(
      report.storage_readback && report.storage_readback.persisted_after_relaunch === true
    ),
    profile_js_deleted: statics.profile_js_exists === false,
    no_forbidden_strings: statics.forbidden_strings_present.length === 0,
    records_api_only: statics.uses_records_api === true && statics.direct_storage_calls === false,
    font_scaled: statics.font_size_all_scaled === true,
    json_ok: statics.json_parses === true && statics.json_title === '个人档案',
  };
  const checksPassed = Object.values(checks).every((v) => v === true);
  log(`summary checks: ${JSON.stringify(checks)}`);

  report.summary = {
    ...checks,
    logic_scenarios_total: logic.result ? logic.result.summary.total : 0,
    logic_scenarios_passed: logic.result ? logic.result.summary.passed : 0,
    passed: checksPassed && allOk === true,
    failed: !(checksPassed && allOk === true),
  };

  const reportPath = path.join(E2E_DIR, 'profile.json');
  fs.writeFileSync(reportPath, JSON.stringify(report, null, 2) + '\n');
  log(`profile evidence: ${reportPath}`);

  return report.summary.passed;
}

