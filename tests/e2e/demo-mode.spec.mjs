// Drives one full send inside the runtime page and returns serializable facts.
function driveInPage(mode, text, stubRequest) {
  return async (args) => {
    const pages = getCurrentPages();
    const page = pages[pages.length - 1];
    const originalRequest = wx.request;
    let count = 0;
    wx.request = function (options) {
      count += 1;
      if (args.stubRequest) {
        setTimeout(function () {
          const url = String(options.url || '');
          if (url.indexOf('/api/extract-memory') !== -1) {
            if (options.success) options.success({ statusCode: 200, data: { candidates: [] } });
            return;
          }
          if (options.success) options.success({ statusCode: 200, data: args.organize });
        }, 0);
        return { abort: function () {} };
      }
      return originalRequest.call(wx, options);
    };
    let facts = {};
    try {
      if (args.mode === 'consult' && page.data.mode !== 'consult') {
        await page.setMode('consult');
      }
      page.onInput({ detail: { value: args.text } });
      const send = await page.onSend();
      facts.preview = {
        reason: send.reason,
        open: page.data.previewOpen,
        demoNotice: page.data.previewDemoNotice,
        titles: page.data.previewSections.map((s) => s.title),
      };
      const confirmed = await page.onConfirmSend();
      const msgs = page.data.messages;
      const last = msgs[msgs.length - 1];
      facts.result = {
        confirmedOk: confirmed.ok,
        kind: confirmed.kind,
        lastKind: last ? last.kind : '',
        blockTitles: last ? last.blocks.map((b) => b.title) : [],
        blocksJson: last ? JSON.stringify(last.blocks) : '',
      };
      facts.status = page.data.aiStatus;
      facts.statusText = page.data.aiStatusText;
      facts.demoMode = page.data.demoMode;
      facts.requests = count;
    } finally {
      wx.request = originalRequest;
    }
    return facts;
  };
}

