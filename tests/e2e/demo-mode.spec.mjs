    runtime_blocks_equal_ok: Boolean(report.determinism && report.determinism.organize_blocks_equal === true && report.determinism.consult_blocks_equal === true),
    same_state_sha256_equal_ok: Boolean(report.determinism && report.determinism.same_state_double_capture_sha256_equal === true),
