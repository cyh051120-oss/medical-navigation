const FORBIDDEN_STRINGS = ['AI 注入', 'health_profile', 'hza_', 'System Prompt', '系统提示词'];

function staticInvariantChecks() {
  const ts = readSafe(path.join(SETTINGS_DIR, 'settings.ts'));
  const wxml = readSafe(path.join(SETTINGS_DIR, 'settings.wxml'));
  const wxss = readSafe(path.join(SETTINGS_DIR, 'settings.wxss'));
  const json = readSafe(path.join(SETTINGS_DIR, 'settings.json'));
  const combined = [ts, wxml, wxss, json].join('\n');

  const forbidden = FORBIDDEN_STRINGS.filter((term) => combined.includes(term));
  const usesRecordsApi = /records\.(preferences|memory)\.(get|update|add|remove|list)\s*\(/.test(ts);
  const directStorage = /wx\.(get|set|remove)StorageSync\s*\(/.test(ts);
  const importsConsentVersion =
    /PRIVACY_NOTICE_VERSION/.test(ts) && /from\s+['"]\.\.\/\.\.\/app['"]/.test(ts);
  const usesDeletionApis =
    /deleteAll\s*\(/.test(ts) && /purgeLegacy\s*\(/.test(ts) && /clearAttachments\s*\(/.test(ts);
  const usesExportWrite = /writeFile\s*\(/.test(ts) && /USER_DATA_PATH/.test(ts);
  const usesOplog = /oplog\.append\s*\(/.test(ts);

  let jsonParses = false;
  let jsonTitle = null;
  try {
    const parsed = JSON.parse(json);
    jsonParses = true;
    jsonTitle = parsed.navigationBarTitleText ?? null;
  } catch {
    jsonParses = false;
  }

  const fontLines = wxss.split(/\r?\n/).filter((line) => line.includes('font-size'));
  const fontAllScaled =
    fontLines.length > 0 && fontLines.every((line) => /calc\([^)]*var\(--mhp-scale\)\)/.test(line));
  const wxmlScaleInline = /--mhp-scale:\s*\{\{scale\}\}/.test(wxml);
  const wxssHighContrastVars = wxss.includes('--mhp-hc-bg') && wxss.includes('--mhp-hc-text');

  return {
    settings_ts_exists: fs.existsSync(path.join(SETTINGS_DIR, 'settings.ts')),
    settings_js_exists: fs.existsSync(path.join(SETTINGS_DIR, 'settings.js')),
    forbidden_strings_present: forbidden,
    uses_records_api: usesRecordsApi,
    direct_storage_calls: directStorage,
    imports_consent_version: importsConsentVersion,
    uses_deletion_apis: usesDeletionApis,
    uses_export_write: usesExportWrite,
    uses_oplog: usesOplog,
    json_parses: jsonParses,
    json_title: jsonTitle,
    font_size_lines: fontLines.length,
    font_size_all_scaled: fontAllScaled,
    wxml_scale_inline: wxmlScaleInline,
    wxss_high_contrast_vars: wxssHighContrastVars,
  };
}

