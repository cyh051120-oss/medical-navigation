const captureScreenshot = makeCaptureScreenshot('settings');

async function renderEvidence(miniProgram, tag) {
  const stack = await miniProgram.pageStack();
  const top = Array.isArray(stack) && stack.length > 0 ? stack[stack.length - 1] : null;
  const shot = await captureScreenshot(miniProgram, tag);
  return {
    pageStack: stack.length,
    topPath: top ? top.path : null,
    topQuery: top ? top.query : null,
    screenshotBytes: shot.bytes,
    screenshotMd5: shot.md5,
    pngMagic: shot.pngMagic,
    ok:
      stack.length >= 1 &&
      top !== null &&
      top.path === SETTINGS_ROUTE &&
      shot.pngMagic &&
      shot.bytes > 5000,
  };
}

async function clearAllNamespaces(miniProgram) {
  for (const raw of ALL_RAW) {
    for (const ns of APP_NAMESPACES) {
      await miniProgram.callWxMethod('removeStorageSync', ns + raw);
    }
  }
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function main() {
  ensureDir(E2E_DIR);
  ensureDir(path.dirname(QA_FAILURE_PATH));
  section('SETTINGS SPEC');

  const failureOnly = process.argv.includes('--simulate-wipe-partial');

  // ---- Layer 1: real page logic ----
  const logic = runLogicHarness();
  const logicScenarios = logic.result ? logic.result.scenarios : [];
  const logicFailed = logic.result ? logic.result.summary.failed : -1;

  if (logic.failure_raw !== '') {
    fs.writeFileSync(QA_FAILURE_PATH, logic.failure_raw);
    log(`failure evidence: ${QA_FAILURE_PATH}`);
  }

  if (failureOnly) {
    process.stdout.write(logic.failure_raw);
    if (logic.result !== null && logicFailed === 0) {
      fail('failure mode: wipe partial-failure scenario did NOT fail as a failure demo');
      process.exit(1);
    }
    process.exit(1);
  }

  const report = {
    command: 'node tests/e2e/settings.spec.mjs',
    timestamp: new Date().toISOString(),
    platform: `${os.platform()} ${os.release()} (${os.arch()})`,
    node_version: process.version,
    project_path: CONFIG.projectPath,
    logic: {
      method: logic.method,
      settings_ts: logic.settings_ts,
      exit: logic.exit,
      result: logic.result,
    },
    render: null,
    render_fontsize: null,
    namespace: null,
    storage_readback: null,
    static_invariants: null,
    summary: null,
  };

  let allOk = true;

  if (logic.result !== null && logic.exit === 0 && logicFailed === 0) {
    ok(`logic harness: ${logic.result.summary.passed}/${logic.result.summary.total} scenarios passed (real page methods)`);
  } else {
    fail(`logic harness failed (exit=${logic.exit}, failed_scenarios=${logicFailed}); stderr tail: ${logic.stderr_tail}`);
    allOk = false;
  }
  for (const scenario of logicScenarios) {
    log(`  [logic] ${scenario.pass ? 'PASS' : 'FAIL'} ${scenario.id}: ${scenario.name}`);
    if (!scenario.pass) allOk = false;
  }

  // ---- Static invariants ----
  const statics = staticInvariantChecks();
  report.static_invariants = {
    settings_ts_exists: statics.settings_ts_exists,
    settings_js_exists: statics.settings_js_exists,
    forbidden_strings_present: statics.forbidden_strings_present,
    uses_records_api: statics.uses_records_api,
    direct_storage_calls: statics.direct_storage_calls,
    imports_consent_version: statics.imports_consent_version,
    uses_deletion_apis: statics.uses_deletion_apis,
    uses_export_write: statics.uses_export_write,
    uses_oplog: statics.uses_oplog,
    json_parses: statics.json_parses,
    json_title: statics.json_title,
    font_size_lines: statics.font_size_lines,
    font_size_all_scaled: statics.font_size_all_scaled,
    wxml_scale_inline: statics.wxml_scale_inline,
    wxss_high_contrast_vars: statics.wxss_high_contrast_vars,
  };
  const staticsOk =
    statics.settings_ts_exists === true &&
    statics.settings_js_exists === false &&
    statics.forbidden_strings_present.length === 0 &&
    statics.uses_records_api === true &&
    statics.direct_storage_calls === false &&
    statics.imports_consent_version === true &&
    statics.uses_deletion_apis === true &&
    statics.uses_export_write === true &&
    statics.uses_oplog === true &&
    statics.json_parses === true &&
    statics.json_title === '设置' &&
    statics.font_size_all_scaled === true &&
    statics.wxml_scale_inline === true &&
    statics.wxss_high_contrast_vars === true;
  if (staticsOk) {
    ok('static invariants: records API only; consent version imported; scale/hc wired; tokens-only scaled wxss');
  } else {
    fail(`static invariant failure: ${JSON.stringify(report.static_invariants)}`);
    allOk = false;
  }

  // ---- Layer 2: runtime ----
  let miniProgram;
  try {
    miniProgram = await launchMiniProgram();
    await clearAllNamespaces(miniProgram);

    // warm-up + settle: the first reLaunch can race onShow render.
    await miniProgram.reLaunch('/' + SETTINGS_ROUTE);
    await delay(800);
    await miniProgram.reLaunch('/' + SETTINGS_ROUTE);
    await delay(800);
    const baseline = await renderEvidence(miniProgram, 'baseline');
    report.render = { ...baseline, method: 'reLaunch+pageStack+screenshot' };
    if (baseline.ok) {
      ok(`render evidence: pageStack=${baseline.pageStack}, top=${baseline.topPath}, bytes=${baseline.screenshotBytes}`);
    } else {
      fail(`render check failed: ${JSON.stringify(baseline)}`);
      allOk = false;
    }

    const prefsLarge = {
      aiEnabled: false,
      consentVersion: null,
      fontSize: 32,
      highContrast: false,
      autoMemory: true,
      updatedAt: '2026-02-01T00:00:00.000Z',
    };

    // positive: mhp_ preferences change the render (font size effect)
    await miniProgram.callWxMethod('setStorageSync', 'mhp_' + RAW_KEYS.preferences, prefsLarge);
    await miniProgram.reLaunch('/' + SETTINGS_ROUTE);
    await delay(800);
    const fontLarge = await renderEvidence(miniProgram, 'font-32');
    const mhpChanged = fontLarge.screenshotMd5 !== baseline.screenshotMd5;
    report.render_fontsize = {
      ...fontLarge,
      namespace: 'mhp_',
      changed_vs_baseline_md5: mhpChanged,
    };

    // negative control: legacy namespace must NOT change the render
    await miniProgram.callWxMethod('removeStorageSync', 'mhp_' + RAW_KEYS.preferences);
    await miniProgram.callWxMethod('setStorageSync', 'hza_' + RAW_KEYS.preferences, prefsLarge);
    await miniProgram.reLaunch('/' + SETTINGS_ROUTE);
    await delay(800);
    const legacyShot = await captureScreenshot(miniProgram, 'legacy-hza');
    await miniProgram.callWxMethod('removeStorageSync', 'hza_' + RAW_KEYS.preferences);
    const hzaChanged = legacyShot.md5 !== baseline.screenshotMd5;

    report.namespace = {
      declared: 'mhp_',
      candidates: APP_NAMESPACES,
      runtime_observed: mhpChanged && !hzaChanged ? 'mhp_' : null,
      empty_baseline_md5: baseline.screenshotMd5,
      observations: {
        mhp_: { md5: fontLarge.screenshotMd5, bytes: fontLarge.screenshotBytes, changed_vs_baseline: mhpChanged },
        hza_: { md5: legacyShot.md5, bytes: legacyShot.bytes, changed_vs_baseline: hzaChanged },
      },
    };

    if (mhpChanged) {
      ok(`font-size 32 render differs from default 14 (md5 ${baseline.screenshotMd5} -> ${fontLarge.screenshotMd5})`);
    } else {
      fail(`font-size change did not change the render: ${JSON.stringify(report.render_fontsize)}`);
      allOk = false;
    }
    if (report.namespace.runtime_observed === 'mhp_') {
      ok('runtime namespace is "mhp_" (mhp_ write changes render; hza_ does not)');
    } else {
      fail(`runtime namespace must be "mhp_" but observed ${JSON.stringify(report.namespace)}`);
      allOk = false;
    }

    // persistence across full close + relaunch
    const persistPrefs = { ...prefsLarge, aiEnabled: true, autoMemory: false };
    await miniProgram.callWxMethod('setStorageSync', 'mhp_' + RAW_KEYS.preferences, persistPrefs);
    await miniProgram.reLaunch('/' + SETTINGS_ROUTE);
    await delay(800);
    try {
      await miniProgram.close();
      log('miniProgram.close() done');
    } catch (err) {
      log(`warning: close failed: ${err?.message || err}`);
    }
    await delay(2000);
    miniProgram = await launchMiniProgram();
    const persisted = await miniProgram.callWxMethod('getStorageSync', 'mhp_' + RAW_KEYS.preferences);
    const persistedOk = JSON.stringify(persisted) === JSON.stringify(persistPrefs);
    report.storage_readback = {
      key: 'mhp_records_preferences',
      written: persistPrefs,
      read_back: persisted,
      matches: persistedOk,
      persisted_after_relaunch: persistedOk,
    };
    if (persistedOk) {
      ok('preferences (fontSize/aiEnabled/autoMemory) persist across full close+relaunch');
    } else {
      fail(`preferences did not persist across relaunch: ${JSON.stringify(persisted)}`);
      allOk = false;
    }

    await clearAllNamespaces(miniProgram);
  } catch (err) {
    fail(`settings spec run error: ${err?.stack || err}`);
    report.error = err?.message || String(err);
    allOk = false;
  } finally {
    if (miniProgram) {
      try {
        await miniProgram.close();
        log('miniProgram.close() done');
      } catch (err) {
        log(`warning: miniProgram.close() failed: ${err?.message || err}`);
      }
    }
  }

  const checks = {
    logic_harness_ok: logic.result !== null && logic.exit === 0 && logicFailed === 0,
    render_ok: report.render ? report.render.ok === true : false,
    font_size_render_changed: Boolean(report.render_fontsize && report.render_fontsize.changed_vs_baseline_md5 === true),
    namespace_observed: report.namespace ? report.namespace.runtime_observed === 'mhp_' : false,
    persistence_ok: Boolean(report.storage_readback && report.storage_readback.persisted_after_relaunch === true),
    static_invariants_ok: staticsOk,
    no_forbidden_strings: statics.forbidden_strings_present.length === 0,
    font_scaled: statics.font_size_all_scaled === true,
    json_ok: statics.json_parses === true && statics.json_title === '设置',
  };
  const checksPassed = Object.values(checks).every((v) => v === true);
  log(`summary checks: ${JSON.stringify(checks)}`);

  report.summary = {
    ...checks,
    logic_scenarios_total: logic.result ? logic.result.summary.total : 0,
    logic_scenarios_passed: logic.result ? logic.result.summary.passed : 0,
    passed: checksPassed && allOk === true,
    failed: !(checksPassed && allOk === true),
  };

  const reportPath = path.join(E2E_DIR, 'settings.json');
  fs.writeFileSync(reportPath, JSON.stringify(report, null, 2) + '\n');
  log(`settings evidence: ${reportPath}`);

  return report.summary.passed;
}

main().then(
  (passed) => {
    process.exit(passed ? 0 : 1);
  },
  (err) => {
    console.error(`[e2e] FAIL ${err?.stack || err}`);
    process.exit(1);
  }
);
