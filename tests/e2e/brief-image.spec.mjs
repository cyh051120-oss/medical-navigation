/** Extract the POSTER copy block from config/texts.ts (so the blanket DISCLAIMERS 免责 copy is excluded). */
function posterCopyBlock() {
  const src = readSafe(TEXTS_TS);
  const start = src.indexOf('export const POSTER');
  if (start === -1) return '';
  const end = src.indexOf('} as const;', start);
  return end === -1 ? src.slice(start) : src.slice(start, end);
}

