/**
 * Race an automator promise against a timeout. The automator Connection has NO reply
 * timeout, so a host call that never invokes its callback (e.g. the devtools album path
 * behind a hidden window) would otherwise hang the whole spec. Resolves — never rejects —
 * with { timedOut } or { value } / { error } so callers can record the truth honestly.
 */

/** Parse width/height from the PNG IHDR (no deps): width at bytes 16-19, height at 20-23 (big-endian). */
function parsePngSize(buffer) {
  if (!hasPngMagic(buffer) || buffer.length < 24) return { width: null, height: null };
  const type = buffer.subarray(12, 16).toString('ascii');
  if (type !== 'IHDR') return { width: null, height: null };
  return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) };
}

