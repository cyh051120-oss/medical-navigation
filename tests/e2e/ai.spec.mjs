function runSourcesHarness() {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'mhp-ai-sources-'));
  const harnessPath = path.join(tmpDir, 'sources.harness.mjs');
  const outPath = path.join(tmpDir, 'sources.json');
  fs.writeFileSync(harnessPath, SOURCES_HARNESS);
  const res = spawnSync(process.execPath, ['--import', 'tsx', harnessPath], {
    cwd: ROOT,
    encoding: 'utf8',
    env: { ...process.env, MHP_ROOT: ROOT, MHP_SOURCES_OUT: outPath },
    timeout: 90000,
    maxBuffer: 16 * 1024 * 1024,
  });
  let parsed = null;
  if (fs.existsSync(outPath)) {
    try {
      parsed = JSON.parse(fs.readFileSync(outPath, 'utf8'));
    } catch (err) {
      fail(`sources harness JSON unparsable: ${err?.message || err}`);
    }
  }
  return { exit: res.status, stderr: `${res.stderr || ''}`.slice(-4000), sources: parsed };
}

