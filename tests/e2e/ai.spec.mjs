function pageConsent(args) {
  const pages = getCurrentPages();
  const page = pages[pages.length - 1];
  const origModal = wx.showModal;
  const origReq = wx.request;
  const modals = [];
  let req = 0;
  wx.showModal = function (o) {
    modals.push({ title: o && o.title, content: o && o.content, confirmText: o && o.confirmText, cancelText: o && o.cancelText });
    if (o && typeof o.success === 'function') o.success({ confirm: args.confirm === true, cancel: args.confirm !== true });
  };
  wx.request = function (o) { req += 1; return origReq.call(wx, o); };
  let switched = null;
  let err = '';
  return Promise.resolve()
    .then(function () { return page.setMode('consult'); })
    .then(function (v) { switched = v; })
    .catch(function (e) { err = String((e && e.message) || e); })
    .then(function () {
      wx.showModal = origModal;
      wx.request = origReq;
      return {
        switched: switched,
        mode: page.data.mode,
        hasConsent: page.hasConsultConsent(),
        ack: wx.getStorageSync('mhp_ai_consult_ack') === true,
        modals: modals,
        requests: req,
        error: err,
      };
    });
}

function pageDrive(args) {
  const pages = getCurrentPages();
  const page = pages[pages.length - 1];
  const origReq = wx.request;
  const origModal = wx.showModal;
  const askBodies = [];
  const modals = [];
  let extractCount = 0;
  wx.request = function (options) {
    const url = String((options && options.url) || '');
    if (url.indexOf('/api/extract-memory') !== -1) extractCount += 1;
    else if (url.indexOf('/api/ask') !== -1) {
      // The evaluate sandbox JSON.parse throws a realm/instanceof error, so capture the raw
      // request string here and parse it back in Node.
      try { askBodies.push(typeof options.data === 'string' ? options.data : ''); } catch (e) { askBodies.push(''); }
    }
    return origReq.call(wx, options);
  };
  wx.showModal = function (o) {
    modals.push({ title: o && o.title });
    if (o && typeof o.success === 'function') o.success({ confirm: args.confirmConsent !== false, cancel: args.confirmConsent === false });
  };
  async function run() {
    const out = { switched: null, modals: modals };
    try {
      page.loadAll();
      if (args.mode && page.data.mode !== args.mode) out.switched = await page.setMode(args.mode);
      if (args.includeProfile === true && page.data.profileAvailable === true && page.data.includeProfile !== true) page.onToggleProfile();
      page.onInput({ detail: { value: args.text } });
      const send = await page.onSend();
      out.send = { reason: send && send.reason, sent: send && send.sent };
      const sections = page.data.previewSections || [];
      out.preview = {
        open: page.data.previewOpen,
        titles: sections.map(function (s) { return s.title; }),
        memoryText: (sections.filter(function (s) { return s.key === 'memories'; })[0] || {}).text || '',
        excerptText: (sections.filter(function (s) { return s.key === 'recordExcerpts'; })[0] || {}).text || '',
      };
      const confirmed = await page.onConfirmSend();
      const msgs = page.data.messages || [];
      const last = msgs[msgs.length - 1];
      out.confirmed = confirmed;
      out.messageCount = msgs.length;
      out.last = last ? {
        kind: last.kind,
        mode: last.mode,
        disclaimer: last.disclaimer,
        errorText: last.errorText,
        canLocalOrganize: last.canLocalOrganize,
        localText: last.localText,
        content: last.content,
        blocks: last.blocks.map(function (b) {
          return {
            type: b.type,
            title: b.title,
            items: b.items.map(function (it) { return { text: it.text, sub: it.sub, url: it.url, tag: it.tag }; }),
          };
        }),
      } : null;
      out.status = page.data.aiStatus;
      out.memoryCount = page.data.memoryCount;
      out.memoryLabel = page.data.memoryLabel;
      out.autoMemoryAdded = page.data.autoMemoryAdded;
      out.autoMemoryHint = page.data.autoMemoryHint;
      out.input = page.data.input;
      out.hint = page.data.hint;
      out.extractCount = extractCount;
      out.askBodiesRaw = askBodies;
    } finally {
      wx.request = origReq;
      wx.showModal = origModal;
    }
    return out;
  }
  return run();
}

function pageRedflags(args) {
  const pages = getCurrentPages();
  const page = pages[pages.length - 1];
  const out = [];
  const origModal = wx.showModal;
  wx.showModal = function (o) { if (o && typeof o.success === 'function') o.success({ confirm: true, cancel: false }); };
  async function loop() {
    try {
      for (let i = 0; i < args.terms.length; i += 1) {
        const term = args.terms[i];
        if (page.data.mode !== 'organize') { try { await page.setMode('organize'); } catch (e) {} }
        page.onInput({ detail: { value: term } });
        await page.onSend();
        const confirmed = await page.onConfirmSend();
        const msgs = page.data.messages || [];
        const last = msgs[msgs.length - 1];
        out.push({
          term: term,
          confirmedKind: confirmed && confirmed.kind,
          kind: last ? last.kind : '',
          disclaimer: last ? last.disclaimer : '',
          blockCount: last ? last.blocks.length : -1,
          blockTypes: last ? last.blocks.map(function (b) { return b.type; }) : [],
          blockTitles: last ? last.blocks.map(function (b) { return b.title; }) : [],
          noticeText: last && last.blocks[0] && last.blocks[0].items[0] ? last.blocks[0].items[0].text : '',
        });
      }
    } finally {
      wx.showModal = origModal;
    }
    return out;
  }
  return loop();
}

