function startMock({ adversarial }) {
  return new Promise((resolve, reject) => {
    const env = { ...process.env };
    delete env.MOCK_PORT;
    delete env.PORT;
    if (adversarial === true) env.MOCK_ADVERSARIAL = '1';
    else delete env.MOCK_ADVERSARIAL;
    const child = spawn('node', [MOCK_SCRIPT], { cwd: ROOT, env, stdio: ['ignore', 'pipe', 'pipe'] });
    let out = '';
    let err = '';
    let settled = false;
    const timer = setTimeout(() => {
      if (settled) return;
      settled = true;
      try { child.kill('SIGKILL'); } catch { /* ignore */ }
      reject(new Error(`mock-upstream start timed out; stderr=${err.slice(-500)}`));
    }, 12000);
    child.stdout.on('data', (d) => {
      out += d.toString();
      const match = /listening on (http:\/\/127\.0\.0\.1:\d+)/.exec(out);
      if (match !== null && settled === false) {
        settled = true;
        clearTimeout(timer);
        resolve({ child, url: match[1], stdout: out, adversarial: adversarial === true });
      }
    });
    child.stderr.on('data', (d) => { err += d.toString(); });
    child.on('exit', (code) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      reject(new Error(`mock-upstream exited early (code=${code}); stderr=${err.slice(-500)}`));
    });
  });
}

