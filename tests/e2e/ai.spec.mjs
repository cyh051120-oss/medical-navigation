let miniProgram = null;

async function evalPage(fn, arg, label, timeoutMs = 30000) {
  const raced = await withTimeout(miniProgram.evaluate(fn, arg), timeoutMs, label);
  if (raced.timedOut === true) {
    fail(`evaluate ${label} timed out`);
    return { __error: 'timed out' };
  }
  if (raced.error !== undefined) {
    fail(`evaluate ${label} failed: ${raced.error}`);
    return { __error: raced.error };
  }
  return raced.value;
}

/** Parse the raw /api/ask request strings captured in the runtime (Node side, where JSON works). */
function parseAskBodies(rawList) {
  if (!Array.isArray(rawList)) return [];
  return rawList.map((raw) => {
    let b = {};
    try {
      b = JSON.parse(String(raw));
    } catch {
      b = {};
    }
    if (b === null || typeof b !== 'object') b = {};
    return {
      mode: b.mode,
      memories: b.memories === undefined ? null : b.memories,
      hasProfile: b.profileSummary !== undefined,
      excerpts: Array.isArray(b.recordExcerpts) ? b.recordExcerpts : null,
      userTexts: Array.isArray(b.messages)
        ? b.messages.filter((m) => m.role === 'user').map((m) => m.content)
        : [],
      raw: typeof raw === 'string' ? raw : '',
    };
  });
}

/** Drive one send through the real page and parse the captured request bodies. */
async function drivePage(args, label, timeoutMs) {
  const d = await evalPage(pageDrive, args, label, timeoutMs);
  if (d && d.__error === undefined) d.askBodies = parseAskBodies(d.askBodiesRaw);
  return d;
}

